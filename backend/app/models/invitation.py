from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy import BigInteger, CheckConstraint, DateTime, ForeignKey, Identity, Index, String, Uuid, func, text
from datetime import datetime
from typing import Literal, Optional
import uuid
from backend.app.models.base import Base

# every Access Level, the same values as the CHECK constraints on invitations and delegations. It's defined here, with
# the model that stores it, so schemas and services import it from the model and the model never imports from them
AccessLevel = Literal["view_only", "full_access"]

# an Owner's offer of a Delegation to one email at one Access Level (ADR 0007).
# Expired isn't stored: it's a pending Invitation whose expires_at has passed, checked against the database's clock
class Invitation(Base):
    __tablename__ = "invitations"

    __table_args__ = (
        # stored lowercased, so matching it against a signed-in email is a plain comparison
        CheckConstraint("invited_email = lower(invited_email)", name="check_invitations_invited_email_lowercase"),
        CheckConstraint("access_level IN ('view_only', 'full_access')", name="check_invitations_access_level"),
        CheckConstraint("status IN ('pending', 'accepted', 'cancelled')", name="check_invitations_status"),
        # a SHA-256 hex digest and nothing else. The raw token is 43 characters, so storing it by mistake fails here
        CheckConstraint("token_hash ~ '^[0-9a-f]{64}$'", name="check_invitations_token_hash_sha256"),
        # each time is set exactly when the Invitation has that status, never otherwise
        CheckConstraint("(status = 'accepted') = (accepted_at IS NOT NULL)", name="check_invitations_accepted_at"),
        CheckConstraint("(status = 'cancelled') = (cancelled_at IS NOT NULL)", name="check_invitations_cancelled_at"),
        # accept finds the Invitation by its token's hash
        Index("index_invitations_token_hash", "token_hash", unique=True),
        # one pending Invitation per Owner and email, even if Send is clicked twice at once.
        # Accepted and cancelled ones don't count, so the same email can be invited again later
        Index(
            "index_invitations_pending_owner_email",
            "owner_id",
            "invited_email",
            unique=True,
            postgresql_where=text("status = 'pending'")
        ),
        # Postgres doesn't index a foreign key on its own. This one serves listing an Owner's Invitations
        Index("index_invitations_owner_id", "owner_id"),
    )

    # always generated by the database, so the app can't choose an id
    id: Mapped[int] = mapped_column(BigInteger, Identity(always=True), primary_key=True)
    # deleting the Owner's account deletes their Invitations with it (ADR 0007)
    owner_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        ForeignKey("app_users.id", ondelete="CASCADE"),
        nullable=False
    )
    invited_email: Mapped[str] = mapped_column(String(254), nullable=False)
    access_level: Mapped[AccessLevel] = mapped_column(String(20), nullable=False)
    # only the hash: the raw token is in the emailed link and nowhere else
    token_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    status: Mapped[str] = mapped_column(String(20), nullable=False, server_default=text("'pending'"))
    # no default: sending and resending set it, 7 days on from the database's now()
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now()
    )
    accepted_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
    cancelled_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
