from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy import BigInteger, CheckConstraint, DateTime, ForeignKey, Identity, Index, String, Uuid, func, text
from datetime import datetime
from typing import Optional
import uuid
from backend.app.models.base import Base

# an Owner's standing permission for one Delegate to reach the Owner's Doctor Cards at one Access Level (ADR 0007).
# Expired isn't stored: it's an active Delegation whose expires_at has passed, checked against the database's clock
class Delegation(Base):
    __tablename__ = "delegations"

    __table_args__ = (
        CheckConstraint("access_level IN ('view_only', 'full_access')", name="check_delegations_access_level"),
        CheckConstraint("status IN ('active', 'revoked')", name="check_delegations_status"),
        # nobody holds a Delegation to their own cards
        CheckConstraint("owner_id <> delegate_id", name="check_delegations_owner_is_not_delegate"),
        # revoked_at is set exactly when the Delegation is revoked, never otherwise
        CheckConstraint("(status = 'revoked') = (revoked_at IS NOT NULL)", name="check_delegations_revoked_at"),
        # one active Delegation per Owner and Delegate. Revoked ones don't count, so the Owner can invite them again
        Index(
            "index_delegations_active_owner_delegate",
            "owner_id",
            "delegate_id",
            unique=True,
            postgresql_where=text("status = 'active'")
        ),
        # one Invitation creates at most one Delegation, even if accept runs twice at once
        Index("index_delegations_invitation_id", "invitation_id", unique=True),
        # Postgres doesn't index a foreign key on its own. These serve looking Delegations up from either side
        Index("index_delegations_owner_id", "owner_id"),
        Index("index_delegations_delegate_id", "delegate_id"),
    )

    # always generated by the database, so the app can't choose an id
    id: Mapped[int] = mapped_column(BigInteger, Identity(always=True), primary_key=True)
    # deleting either person's account deletes the Delegation with it (ADR 0007)
    owner_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        ForeignKey("app_users.id", ondelete="CASCADE"),
        nullable=False
    )
    delegate_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        ForeignKey("app_users.id", ondelete="CASCADE"),
        nullable=False
    )
    # the Invitation whose acceptance created it. No ON DELETE: deleting that Invitation is refused,
    # except along with the Owner's account, which deletes both
    invitation_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("invitations.id"), nullable=False)
    access_level: Mapped[str] = mapped_column(String(20), nullable=False)
    status: Mapped[str] = mapped_column(String(20), nullable=False, server_default=text("'active'"))
    # empty for now: nothing sets it yet, and an empty one never expires
    expires_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now()
    )
    revoked_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
