from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy import BigInteger, CheckConstraint, DateTime, Identity, Integer, String, Uuid, func
from sqlalchemy.dialects.postgresql import JSONB
from datetime import datetime
from typing import Optional
import uuid
from backend.app.models.base import Base

# the Audit Log: the app only ever adds rows, and database triggers reject any update, delete or truncate (ADR 0007)
class AuditLog(Base):
    __tablename__ = "audit_log"

    __table_args__ = (
        # the same actions as AuditAction in services/audit_log.py
        CheckConstraint(
            "action IN ('add_card', 'edit_card', 'delete_card', "
            "'send_invitation', 'resend_invitation', 'cancel_invitation', 'accept_invitation')",
            name="check_audit_log_action"
        ),
    )

    # always generated by the database, so the app can't choose an id
    id: Mapped[int] = mapped_column(BigInteger, Identity(always=True), primary_key=True)
    # set by the database when the row is added, never passed in
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now()
    )
    # plain ids and the email, with no foreign keys: an entry has to outlive the person and card it's about
    actor_id: Mapped[uuid.UUID] = mapped_column(Uuid, nullable=False)
    actor_email: Mapped[str] = mapped_column(String(254), nullable=False)
    action: Mapped[str] = mapped_column(String(50), nullable=False)
    owner_id: Mapped[Optional[uuid.UUID]] = mapped_column(Uuid)
    card_id: Mapped[Optional[int]] = mapped_column(Integer)
    # for an edit, {"fields": [...]}: the names of the fields that changed, never their values
    details: Mapped[Optional[dict]] = mapped_column(JSONB)
